import Foundation
import Synchronization

/// Compatibility with the cron producer at Hermes 4a0eaf79 / ca678285.
/// Text never establishes provenance: callers must also verify internal_notification.
nonisolated enum HermesMessagePresentation {
    // Regex literals compile at runtime; retain them for callers across actors.
    private static let scheduledHeader = Mutex(/\[Cronjob "([^"\r\n\x00-\x1F]+)" output — scheduled job, not the user\. Review it, act on anything that needs action, and summarize for the chat\.\]\n\n/)
    private static let senderHeader = Mutex(#/Message from 🤖 ([^\r\n\x00-\x1F]+?) \(@([A-Za-z0-9_@\-\/\.]+)\): /#)

    static func isMachinery(_ kind: String?) -> Bool {
        ["internal_notification", "async_delegation_complete", "process_complete"].contains(kind ?? "")
    }

    static func scheduledJobName(_ text: String) -> String? {
        // Bound header work independently of potentially very large diagnostic bodies.
        let header = String(text.prefix(1024))
        return scheduledHeader.withLock { expression in
            guard let match = header.prefixMatch(of: expression),
                  !match.1.trimmingCharacters(in: .whitespaces).isEmpty,
                  !match.1.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains),
                  !match.1.unicodeScalars.contains(where: CharacterSet.newlines.contains),
                  !text.dropFirst(match.0.count).isEmpty else { return nil }
            return String(match.1)
        }
    }

    static func senderStamp(_ text: String) -> (sender: ChatMessage.MessageSender, length: Int)? {
        let header = String(text.prefix(1024))
        return senderHeader.withLock { expression in
            guard let match = header.prefixMatch(of: expression),
                  !match.1.trimmingCharacters(in: .whitespaces).isEmpty else { return nil }
            return (ChatMessage.MessageSender(name: String(match.1), handle: String(match.2)), match.0.count)
        }
    }

    // Hermes gateway/response_filters.py's interactive whole-response rule.
    // Do not use the looser cron producer prefix rule on replies in a human chat.
    private static let markers: Set<String> = ["[SILENT]", "SILENT", "NO_REPLY", "NO REPLY", "[静默]", "静默", "[沉默]", "沉默"]
    static func isSilence(_ text: String, partial: Bool = false) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.count <= 64 else { return false }
        func edgePunctuation(_ c: Character) -> Bool {
            c != "[" && c != "]" && c.unicodeScalars.allSatisfy(CharacterSet.punctuationCharacters.contains)
        }
        let depunctuated = String(trimmed.drop(while: edgePunctuation).reversed().drop(while: edgePunctuation).reversed())
        return [trimmed, depunctuated].contains { value in
            let canonical = value.uppercased().split(whereSeparator: \.isWhitespace).joined(separator: " ")
            guard !canonical.isEmpty else { return false }
            return partial ? markers.contains { $0.hasPrefix(canonical) } : markers.contains(canonical)
        }
    }
}

public extension ChatMessage {
    struct MessageNotification: Equatable, Sendable {
        public let title: String
        public let systemImage: String
        public let isRoutine: Bool
    }
    struct MessageSender: Equatable, Sendable {
        public let name: String
        public let handle: String
        public var label: String { "From \(name) · @\(handle)" }
    }

    /// Hermes bot_mode_dm.py adds this stamp; a human paste never establishes authorship.
    private var senderStamp: (sender: MessageSender, length: Int)? {
        guard role == .user, displayKind == "internal_notification" else { return nil }
        return HermesMessagePresentation.senderStamp(text)
    }
    var botSender: MessageSender? { senderStamp?.sender }
    var attributedText: String {
        guard let stamp = senderStamp else { return text }
        var body = String(text.dropFirst(stamp.length))
        let footer = "\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]"
        if body.hasSuffix(footer) { body.removeLast(footer.count) }
        return body
    }
    var notificationPresentation: MessageNotification? {
        guard role == .user, attachments.isEmpty, botSender == nil else { return nil }
        if let name = scheduledJobName {
            return .init(title: "Scheduled check · \(name)", systemImage: "clock.arrow.circlepath", isRoutine: true)
        }
        let fallback: String
        let image: String
        switch displayKind {
        case "async_delegation_complete": fallback = "Background agents finished"; image = "person.2"
        case "process_complete": fallback = "Background process finished"; image = "checkmark.circle"
        case "internal_notification":
            return .init(title: "Hermes update", systemImage: "info.circle", isRoutine: false)
        default: return nil
        }
        let title = displayText?.trimmingCharacters(in: .whitespacesAndNewlines)
        let compactTitle = title.flatMap { value -> String? in
            guard !value.isEmpty, value.count <= 80,
                  !value.contains(where: { $0.isNewline || "/\\`$;|".contains($0) }) else { return nil }
            let label = value.lowercased()
            let backgroundHeading = label.hasPrefix("background ") && (label.hasSuffix("finished") || label.hasSuffix("failed"))
            let delegationHeading = label.hasPrefix("subagent task complete: ") || label.hasPrefix("subagent task failed: ")
            return backgroundHeading || delegationHeading ? value : nil
        }
        let heading = title?.split(whereSeparator: \.isNewline).first?.lowercased() ?? ""
        let failed = heading.hasPrefix("background process failed") || heading.hasPrefix("subagent task failed")
        let semanticTitle = failed ? (displayKind == "process_complete" ? "Background process failed" : "Background agents failed") : fallback
        return .init(title: compactTitle ?? semanticTitle, systemImage: image, isRoutine: false)
    }
    var isOutgoingUserMessage: Bool {
        role == .user && !HermesMessagePresentation.isMachinery(displayKind)
    }
    var scheduledJobName: String? {
        guard role == .user, displayKind == "internal_notification", attachments.isEmpty else { return nil }
        return HermesMessagePresentation.scheduledJobName(text)
    }
    var isVisible: Bool {
        if displayKind == "failed_turn" { return true }
        if role == .assistant, attachments.isEmpty, HermesMessagePresentation.isSilence(text) { return false }
        if isSilent == true {
            return role == .assistant && HermesMessagePresentation.isSilence(text, partial: true)
        }
        return true
    }
    /// Shared by unread evidence, previews, and transcript following.
    /// Tool results and failure notes keep their existing attention behavior.
    var requiresAttention: Bool { isVisible && notificationPresentation?.isRoutine != true }
}

public extension Conversation {
    var visibleMessages: [ChatMessage] { messages.filter(\.isVisible) }
    var attentionMessages: [ChatMessage] { messages.filter(\.requiresAttention) }
}
