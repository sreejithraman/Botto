import Foundation
import Testing
@testable import BottoCore

struct MessageAttributionTests {
    @Test(arguments: [ChatMessage.Role.user, .assistant, .tool, .system])
    func unrelatedHiddenRowsKeepTheirExplicitVisibility(_ role: ChatMessage.Role) {
        let message = ChatMessage(id: "hidden", role: role, text: "Hidden duplicate payload", isSilent: true)
        #expect(!message.isVisible)
    }
    @Test func backgroundCompletionChangesPresentationWithoutLosingAttentionOrPayload() throws {
        let payload = "[ASYNC DELEGATION BATCH COMPLETE — deleg_example]\nFull background result"
        let messages = HermesConversationState.messages([
            .object(["row_id": .number(1), "role": .string("user"), "content": .string(payload),
                     "display_kind": .string("async_delegation_complete"),
                     "display_metadata": .object(["display_text": .string("Background review finished")])])
        ], stored: "chat")
        let message = try #require(messages.first)
        #expect(message.text == payload)
        #expect(message.requiresAttention)
        #expect(!message.isOutgoingUserMessage)
        #expect(message.notificationPresentation?.title == "Background review finished")
        #expect(try JSONDecoder().decode(ChatMessage.self, from: JSONEncoder().encode(message)) == message)
    }

    @Test func botDeliveryShowsItsSenderAndBodyWithoutTheMachineFooter() throws {
        let body = "Please own the incident follow-up."
        let payload = "Message from 🤖 Gustavo (@hermes): " + body + "\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]"
        let message = try #require(HermesConversationState.messages([
            .object(["role": .string("user"), "content": .string(payload), "display_kind": .string("internal_notification")])
        ], stored: "chat").first)
        #expect(message.botSender?.name == "Gustavo")
        #expect(message.botSender?.handle == "hermes")
        #expect(message.attributedText == body)
        #expect(!message.isOutgoingUserMessage)
        #expect(message.notificationPresentation == nil)
        #expect(message.requiresAttention)
        #expect(message.text == payload)
    }

    @Test(arguments: [nil, "user", "steer", "unknown"] as [String?])
    func humanPastesRemainHuman(_ kind: String?) {
        for text in ["Message from 🤖 Gustavo (@hermes): Please inspect this.",
                     "[ASYNC DELEGATION BATCH COMPLETE — deleg_example]\nFull result",
                     "[IMPORTANT: Background process proc_example completed normally (exit code 0).]"] {
            let message = ChatMessage(id: "human", role: .user, text: text, displayKind: kind)
            #expect(message.isOutgoingUserMessage)
            #expect(message.botSender == nil)
            #expect(message.notificationPresentation == nil)
            #expect(message.requiresAttention)
        }
    }

    @Test(arguments: ["internal_notification", "async_delegation_complete", "process_complete"])
    func assistantControlRepliesStayQuietAfterEveryInput(_ kind: String) {
        let messages = HermesConversationState.messages([
            .object(["role": .string("user"), "content": .string("Machine work"), "display_kind": .string(kind)]),
            .object(["role": .string("assistant"), "content": .string("[SILENT]")]),
            .object(["role": .string("user"), "content": .string("A human question")]),
            .object(["role": .string("assistant"), "content": .string("[SILENT]")])
        ], stored: "chat")
        #expect(!messages[1].isVisible)
        #expect(!messages[3].isVisible)
    }

    @Test func genericInternalNotesStayReadableAndNeverBecomeOutgoingBubbles() {
        let message = ChatMessage(id: "note", role: .user, text: "A gateway notice", displayKind: "internal_notification")
        #expect(!message.isOutgoingUserMessage)
        #expect(message.notificationPresentation?.title == "Hermes update")
        #expect(message.isVisible && message.requiresAttention)
    }
    @Test func queueSourceHintsNeverAuthorizeTranscriptProvenance() throws {
        var state = HermesConversationState(profile: "bot", root: "stored", stored: "stored", runtime: "runtime", epoch: "epoch")
        state.applyPending(.array([.object([
            "admission_id": .string("background-admission"), "status": .string("queued"),
            "input_id": .string(#"["completion","proc_sample",100]"#), "text": .string("Machine result")
        ])]))
        state.reduce(.object(["type": .string("message.start"), "admission_id": .string("background-admission"),
                              "payload": .object([:])]), authority: true)
        #expect(state.conversation.messages.isEmpty, "Only host metadata may create an attributed transcript row")
        state.reduce(.object(["type": .string("message.delta"), "payload": .object(["text": .string("[SILENT]")])]), authority: true)
        #expect(state.conversation.messages.last?.isVisible == false)
    }

    @Test(arguments: ["async_delegation_complete", "process_complete"])
    func failedBackgroundEventsKeepAttention(_ kind: String) {
        let message = ChatMessage(id: "failed", role: .user, text: "The background task failed.",
            displayKind: kind, displayText: "Subagent Task Failed: Review changes")
        #expect(message.requiresAttention)
        #expect(message.notificationPresentation?.title == "Subagent Task Failed: Review changes")
        #expect(!message.isOutgoingUserMessage)
    }

    @Test func remoteBotStampPreservesTheQualifiedHandleForAnIncomingParticipant() {
        let message = ChatMessage(id: "remote", role: .user,
            text: "Message from 🤖 Gustavo (@hermes@office): The check is complete.", displayKind: "internal_notification")
        #expect(message.botSender?.name == "Gustavo")
        #expect(message.botSender?.handle == "hermes@office")
        #expect(message.attributedText == "The check is complete.")
        #expect(!message.isOutgoingUserMessage)
    }

}

@Test(arguments: ["process_complete", "async_delegation_complete"])
func machineryCommandLabelsStayCompactWithoutLosingDetails(_ kind: String) throws {
    let command = "/Users/example/bin/diagnose --all\n" + String(repeating: "health check details\n", count: 50)
    let title = kind == "process_complete" ? "Background Process Finished: " : "Subagent Task Complete: "
    let message = try #require(HermesConversationState.messages([
        .object(["role": .string("user"), "content": .string(command), "display_kind": .string(kind),
                 "display_metadata": .object(["display_text": .string(title + command)])])
    ], stored: "stored").first)
    #expect(message.notificationPresentation?.title == (kind == "process_complete" ? "Background process finished" : "Background agents finished"))
    #expect(message.text == command)
    #expect(message.displayText == title + command)
    #expect(message.requiresAttention)
}

@Test func plainCommandCannotBecomeTheNotificationTitle() {
    let message = ChatMessage(id: "process", role: .user, text: "Process output",
        displayKind: "process_complete", displayText: "echo hello")
    #expect(message.notificationPresentation?.title == "Background process finished")
}
