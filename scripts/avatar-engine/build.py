#!/usr/bin/env python3
"""Build the pinned DOM-free Open Bot Avatar engine and static preset frames."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
REVISION = "3a5119877844165eebafe57d3100da475f67d0a8"
HEADER = f"// Open Bot Avatar {REVISION}; MIT, copyright (c) 2026 Dominik Scholz.\n// Generated by scripts/avatar-engine/build.py; do not edit.\n"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((HERE / "UPSTREAM.json").read_text())
    for name, expected in manifest["files"].items():
        actual = hashlib.sha256((HERE / "upstream" / name).read_bytes()).hexdigest()
        if actual != expected: raise SystemExit(f"Pinned upstream source changed: {name}")
    resources = ROOT / "Sources/BottoCore/Resources"
    with tempfile.TemporaryDirectory(prefix="botto-avatar-engine-") as scratch:
        bundle = Path(scratch) / "engine.js"
        subprocess.run(["npm", "exec", "--yes", "--package=esbuild@0.28.2", "--", "esbuild",
                        str(HERE / "bridge.ts"), "--bundle", "--format=iife", "--global-name=BottoAvatarEngine",
                        "--target=es2020", "--minify", "--legal-comments=none", f"--outfile={bundle}"], check=True, cwd=ROOT)
        engine = (HEADER + bundle.read_text()).encode()
        destination = resources / "OpenBotAvatarEngine.js"
        if args.check:
            if destination.read_bytes() != engine: raise SystemExit("OpenBotAvatarEngine.js is stale")
        else: destination.write_bytes(engine)
        catalog = resources / "HermesAvatarDefinitions.json"
        if catalog.exists():
            script = """
const fs = require('node:fs'), vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), context);
const definitions = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const assets = definitions.map(definition => {
  const asset = context.BottoAvatarEngine.prepareValue(JSON.stringify(definition),6);
  const used = new Set(asset.restingFrame.shapes.filter(shape => shape.kind === 'slice').map(shape => shape.path));
  return {...asset, key:asset.key+'|bundled-rest', isRestingPreview:true,
    paths:Object.fromEntries(Object.entries(asset.paths).filter(([id]) => used.has(id)))};
});
process.stdout.write(JSON.stringify(assets));
"""
            assets = subprocess.check_output(["node", "-e", script, str(bundle), str(catalog)], cwd=ROOT)
            destination = resources / "HermesAvatarFrames.json"
            if args.check:
                if destination.read_bytes() != assets: raise SystemExit("HermesAvatarFrames.json is stale")
            else: destination.write_bytes(assets)
    print("Open Bot Avatar bundle and preset frames match" if args.check else "Built Open Bot Avatar bundle and preset frames")

if __name__ == "__main__": main()
